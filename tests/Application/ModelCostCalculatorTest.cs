using MarketAssistant.Agents.TokenManagement;
using MarketAssistant.Applications.Settings;
using MarketAssistant.Services.Cost;

namespace TestMarketAssistant.Application;

/// <summary>
/// <see cref="ModelCostCalculator"/> 单元测试：成本计算、未定价处理、
/// "provider|model" 精确匹配与展示文本格式。
/// </summary>
[TestClass]
public sealed class ModelCostCalculatorTest
{
    private static AnalysisTokenUsage CreateUsage(params (string Agent, long Input, long Output)[] entries)
    {
        var usage = new AnalysisTokenUsage
        {
            InputTokens = entries.Sum(e => e.Input),
            OutputTokens = entries.Sum(e => e.Output),
            CallCount = entries.Length
        };
        usage.Entries.AddRange(entries.Select(e => new TokenUsageEntry
        {
            AgentName = e.Agent,
            InputTokens = e.Input,
            OutputTokens = e.Output,
            CallCount = 1
        }));
        return usage;
    }

    private static List<ModelPrice> CreatePrices(
        string provider,
        string model,
        decimal inputPrice,
        decimal outputPrice)
        => [new ModelPrice
        {
            ProviderId = provider,
            ModelId = model,
            InputPricePerMillionTokens = inputPrice,
            OutputPricePerMillionTokens = outputPrice
        }];

    [TestMethod]
    [TestCategory("Unit")]
    public void DefaultCatalog_ShouldProvideMatchableNonNegativePrices()
    {
        Assert.IsNotEmpty(DefaultModelPriceCatalog.Defaults, "内置参考价不应为空，否则成本可见在开箱状态下失效");

        foreach (var price in DefaultModelPriceCatalog.Defaults)
        {
            Assert.IsTrue(price.IsMatchable,
                $"参考价 {price.ProviderId}/{price.ModelId} 缺少必填字段或价格非法");
            Assert.IsTrue(price.InputPricePerMillionTokens >= 0m);
            Assert.IsTrue(price.OutputPricePerMillionTokens >= 0m);
        }
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void DefaultCatalog_ShouldNotContainDuplicateProviderModelPairs()
    {
        var duplicates = DefaultModelPriceCatalog.Defaults
            .GroupBy(price => (price.ProviderId, price.ModelId))
            .Where(group => group.Count() > 1)
            .Select(group => $"{group.Key.ProviderId}/{group.Key.ModelId}")
            .ToList();

        Assert.AreEqual(0, duplicates.Count,
            $"参考价表存在重复键会导致覆盖匹配歧义：{string.Join(", ", duplicates)}");
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void DefaultCatalog_CoveredModels_ShouldProduceNonZeroCost()
    {
        // 回归防护：内置参考价若全部为 0，成本展示会退回"未定价"，
        // 等于没修复 P0-2 的开箱承诺。
        var usage = CreateUsage(("Any", 1_000_000, 1_000_000));
        var estimate = ModelCostCalculator.Estimate(
            usage,
            DefaultModelPriceCatalog.Defaults,
            _ => $"{DefaultModelPriceCatalog.Defaults[0].ProviderId}|{DefaultModelPriceCatalog.Defaults[0].ModelId}");

        Assert.IsTrue(estimate.TotalCost > 0m, "内置参考价应能算出非零成本");
        Assert.IsFalse(estimate.HasUnpriced);
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void CreateDefaults_ShouldReturnIndependentInstances()
    {
        var first = DefaultModelPriceCatalog.CreateDefaults();
        var second = DefaultModelPriceCatalog.CreateDefaults();

        Assert.AreNotSame(first[0], second[0], "参考价是可变对象，必须逐次返回独立副本");

        first[0].InputPricePerMillionTokens = 999m;
        Assert.AreNotEqual(999m, second[0].InputPricePerMillionTokens,
            "修改一份副本不应污染另一份（设置页会就地编辑）");
        Assert.AreNotEqual(999m, DefaultModelPriceCatalog.Defaults[0].InputPricePerMillionTokens,
            "修改副本不应污染内置常量表");
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void FillIfEmpty_EmptyList_ShouldSeedDefaults()
    {
        var seeded = DefaultModelPriceCatalog.FillIfEmpty([]);

        Assert.AreEqual(DefaultModelPriceCatalog.Defaults.Count, seeded.Count);
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void FillIfEmpty_NullOrExisting_ShouldNotOverwrite()
    {
        // null 视同"未配置"，同样填入参考价：反序列化缺字段时即为 null，
        // 若此时返回 null 会让成本展示直接 NRE。
        var fromNull = DefaultModelPriceCatalog.FillIfEmpty(null);
        Assert.AreEqual(DefaultModelPriceCatalog.Defaults.Count, fromNull.Count,
            "null（反序列化缺字段）应与空列表同等对待，填入参考价");

        // 用户已维护的价格表必须原样保留
        var userPrices = CreatePrices("MyProvider", "my-model", 1m, 2m);
        var result = DefaultModelPriceCatalog.FillIfEmpty(userPrices);

        Assert.AreEqual(1, result.Count, "用户已维护的价格表必须原样保留，不得被内置值覆盖");
        Assert.AreEqual("my-model", result[0].ModelId);
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void UserSetting_BriefingSwitches_ShouldDefaultToEnabled()
    {
        // 默认开启：保持 v1.0-beta 已交付的留存钩子行为不变，
        // 开关是给用户的控制权，不应让升级用户静默失去该功能。
        var setting = new UserSetting();

        Assert.IsTrue(setting.EnableDailyBriefing, "简报功能默认应为开启");
        Assert.IsTrue(setting.AutoGenerateDailyBriefing, "自动生成默认应为开启");
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void UserSetting_Clone_ShouldCarryBriefingSwitches()
    {
        // 草稿模式依赖 Clone：漏拷会让设置页保存后开关静默失效。
        var setting = new UserSetting
        {
            EnableDailyBriefing = false,
            AutoGenerateDailyBriefing = false
        };

        var clone = setting.Clone();

        Assert.IsFalse(clone.EnableDailyBriefing, "Clone 必须携带简报总开关");
        Assert.IsFalse(clone.AutoGenerateDailyBriefing, "Clone 必须携带自动生成开关");
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void UserSetting_Clone_ShouldDeepCopyModelPrices()
    {
        var setting = new UserSetting
        {
            ModelPrices = CreatePrices("p", "m", 1m, 2m)
        };

        var clone = setting.Clone();
        clone.ModelPrices[0].InputPricePerMillionTokens = 99m;

        Assert.AreEqual(1m, setting.ModelPrices[0].InputPricePerMillionTokens,
            "价格表必须深拷贝，否则草稿编辑会直接污染已保存设置");
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void Estimate_WithPrices_ShouldComputeCostPerEntry()
    {
        var usage = CreateUsage(("TechnicalAnalyst", 1_000_000, 100_000));
        var prices = CreatePrices("openai", "gpt-test", 2m, 8m);

        var estimate = ModelCostCalculator.Estimate(usage, prices, _ => "openai|gpt-test");

        Assert.AreEqual(2m + 0.8m, estimate.TotalCost, "成本 = 输入1M×2 + 输出0.1M×8");
        Assert.IsFalse(estimate.HasUnpriced);
        Assert.IsTrue(estimate.HasValue);
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void Estimate_ResolverReturnsNull_ShouldMarkUnpricedWithoutCost()
    {
        var usage = CreateUsage(("TechnicalAnalyst", 1_000_000, 100_000));
        var prices = CreatePrices("openai", "gpt-test", 2m, 8m);

        var estimate = ModelCostCalculator.Estimate(usage, prices, _ => null);

        Assert.AreEqual(0m, estimate.TotalCost);
        Assert.IsTrue(estimate.HasUnpriced, "无法确定模型时必须标记未定价，不得猜测价格");
        Assert.IsFalse(estimate.Lines[0].IsPriced);
        Assert.AreEqual(string.Empty, ModelCostCalculator.FormatCost(estimate), "无已定价消耗不展示金额");
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void Estimate_ModelNotInPriceTable_ShouldMarkUnpriced()
    {
        var usage = CreateUsage(("TechnicalAnalyst", 500_000, 50_000));
        var prices = CreatePrices("openai", "gpt-test", 2m, 8m);

        var estimate = ModelCostCalculator.Estimate(usage, prices, _ => "openai|gpt-other");

        Assert.AreEqual(0m, estimate.TotalCost);
        Assert.IsTrue(estimate.HasUnpriced);
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void Estimate_PartiallyPriced_ShouldSumOnlyPricedLines()
    {
        var usage = CreateUsage(
            ("TechnicalAnalyst", 1_000_000, 0),
            ("FinancialAnalyst", 1_000_000, 0));
        var prices = CreatePrices("openai", "gpt-test", 1m, 1m);

        var estimate = ModelCostCalculator.Estimate(usage, prices,
            agent => agent == "TechnicalAnalyst" ? "openai|gpt-test" : null);

        Assert.AreEqual(1m, estimate.TotalCost, "只累计已定价条目");
        Assert.IsTrue(estimate.HasUnpriced);
        Assert.IsTrue(ModelCostCalculator.FormatCost(estimate).StartsWith("≥ ¥", StringComparison.Ordinal),
            "存在未定价条目时金额应标记为下界");
        Assert.Contains("部分未定价", ModelCostCalculator.FormatCost(estimate));
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void Estimate_ProviderPrefixMismatch_ShouldFallBackToModelIdMatch()
    {
        var usage = CreateUsage(("TechnicalAnalyst", 1_000_000, 1_000_000));
        var prices = CreatePrices("openai", "gpt-test", 3m, 3m);

        // resolver 只给模型 ID（无 provider 前缀）时按模型 ID 兜底匹配
        var estimate = ModelCostCalculator.Estimate(usage, prices, _ => "gpt-test");

        Assert.AreEqual(6m, estimate.TotalCost);
        Assert.IsFalse(estimate.HasUnpriced);
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void Estimate_NullOrEmptyUsage_ShouldReturnEmptyEstimate()
    {
        var prices = CreatePrices("openai", "gpt-test", 1m, 1m);

        var estimate = ModelCostCalculator.Estimate(null, prices, _ => "openai|gpt-test");

        Assert.IsFalse(estimate.HasValue);
        Assert.AreEqual(0m, estimate.TotalCost);
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void Estimate_IncompletePriceRow_ShouldBeIgnored()
    {
        var usage = CreateUsage(("TechnicalAnalyst", 1_000_000, 1_000_000));
        var prices = new List<ModelPrice>
        {
            new() { ProviderId = "openai", ModelId = "", InputPricePerMillionTokens = 1m, OutputPricePerMillionTokens = 1m }
        };

        var estimate = ModelCostCalculator.Estimate(usage, prices, _ => "openai");

        Assert.IsTrue(estimate.HasUnpriced, "缺模型 ID 的残行不得参与匹配");
    }

    [TestMethod]
    [TestCategory("Unit")]
    public void FormatCost_SmallAmount_ShouldUseHighPrecision()
    {
        var usage = CreateUsage(("TechnicalAnalyst", 1_000, 500));
        var prices = CreatePrices("openai", "gpt-test", 1m, 1m);

        var estimate = ModelCostCalculator.Estimate(usage, prices, _ => "openai|gpt-test");

        // 0.0015 元 → 四位小数展示
        Assert.AreEqual("约 ¥0.0015", ModelCostCalculator.FormatCost(estimate));
    }
}
